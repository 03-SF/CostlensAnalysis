import { useState } from "react";
import { fetchAISummary, type AISummaryResponse } from "../services/aiSummaryService";
import type { ProjectSummary } from "../services/calculations";

type AISummaryPanelProps = {
  projectName: string;
  summary: ProjectSummary;
  onSummaryGenerated?: (text: string) => void;
};

export default function AISummaryPanel({ projectName, summary, onSummaryGenerated }: AISummaryPanelProps) {
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<AISummaryResponse | null>(null);
  const [error, setError] = useState<string | null>(null);

  async function handleGenerate() {
    setLoading(true);
    setError(null);
    try {
      const data = await fetchAISummary(projectName, summary);
      setResult(data);
      onSummaryGenerated?.(data.summary);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Could not generate the summary.");
    } finally {
      setLoading(false);
    }
  }

  if (summary.totals.count === 0) return null;

  return (
    <div className="cl-ai-panel mb-4">
      <div className="d-flex flex-column flex-sm-row justify-content-between align-items-sm-start gap-3 mb-2">
        <div>
          <h2 className="h5 mb-1">AI budget summary</h2>
          <p className="text-secondary small mb-0">
            A plain-language overview of how this project is tracking against its budget.
          </p>
        </div>
        {!result && !loading && (
          <button type="button" className="btn btn-primary" onClick={handleGenerate}>
            Generate AI Summary
          </button>
        )}
        {result && (
          <button type="button" className="btn btn-outline-secondary" onClick={handleGenerate} disabled={loading}>
            {loading ? "Regenerating..." : "Regenerate"}
          </button>
        )}
      </div>

      {loading && (
        <div className="d-flex align-items-center gap-2 py-3">
          <span className="spinner-border spinner-border-sm" />
          <span className="text-secondary">Analyzing budget data...</span>
        </div>
      )}

      {error && (
        <div className="alert alert-danger" role="alert">
          {error}
        </div>
      )}

      {result && !loading && (
        <div className="cl-ai-summary-text">
          <p className="mb-2">{result.summary}</p>
          <span className="cl-ai-source-badge">
            {result.source === "ai" ? "Generated by AI" : "Generated from budget rules"}
          </span>
        </div>
      )}
    </div>
  );
}
